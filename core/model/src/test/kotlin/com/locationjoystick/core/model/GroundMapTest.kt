    @Test
    fun matchesBenchGoldens() {
        assertEquals(54, goldens.size)
        for (g in goldens) {
            val o = map(g).pixelToGround(g.x, g.y)!!
            assertEquals(g.east, o.eastMeters, 1e-6)
            assertEquals(g.north, o.northMeters, 1e-6)
        }
    }

    @Test
    fun groundToPixelInvertsPixelToGround() {
        for (g in goldens) {
            val m = map(g)
            val o = m.pixelToGround(g.x, g.y)!!
            val p = m.groundToPixel(o.eastMeters, o.northMeters)
            assertEquals(g.x, p.first, 1e-6)
            assertEquals(g.y, p.second, 1e-6)
        }
    }

    @Test
    fun feetPixelIsOrigin() {
        val m = GroundMap(GroundCalibration(-20.0, 7.5, 3.1, -0.0022, 540.0, 1510.0), 1080.0, 2400.0)
        val o = m.pixelToGround(540.0, 1510.0 * 2400 / 2340)!!
        assertEquals(0.0, o.eastMeters, 1e-9)
        assertEquals(0.0, o.northMeters, 1e-9)
    }

    @Test
    fun beyondHorizonLineIsNull() {
        val m = GroundMap(GroundCalibration(0.0, 7.5, 3.1, -0.0022, 540.0, 1510.0), 1080.0, 2340.0)
        assertNotNull(m.pixelToGround(540.0, 800.0))
        // Horizon (ground at infinity) sits near row -1200 for these terms; rows past it are unreachable.
        assertNull(m.pixelToGround(540.0, -3000.0))
    }

    @Test
    fun nonPositiveScreenThrows() {
        val cal = GroundCalibration(0.0, 7.5, 3.1, -0.0022, 540.0, 1510.0)
        assertThrows(IllegalArgumentException::class.java) { GroundMap(cal, 0.0, 2340.0) }
        assertThrows(IllegalArgumentException::class.java) { GroundMap(cal, 1080.0, -1.0) }
